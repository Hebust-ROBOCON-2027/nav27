// ============================================================================
// R2 上位机 <-> 电控 串口通信协议 v2.2（27 赛季 · 舵轮底盘）
//
// 版本：v2.2（本版为最终约定版本，双方以本文件为准）
//
// 帧结构：帧头 + 命令字 + 长度 + 数据 + CRC
//
// 物理层：UART TTL 3.3V | 波特率 115200 | 8N1（8 数据位，无校验，1 停止位）
// 字节序：小端（Little-Endian）
// 校验：CRC-16/Modbus（poly 0xA001，初值 0xFFFF，低字节在前）
//
// ============================================================================
// 帧格式
// ============================================================================
//
//   | 帧头 2B | 命令字 1B | 长度 1B | 数据 N B | CRC 2B |
//   | AA  55  |    CMD    |   LEN   |   DATA   | CRC16  |
//
//   帧总长 = LEN + 6
//
// ============================================================================
// 帧头为什么用 0xAA 0x55（两字节）
// ============================================================================
//
//   单字节帧头误判概率太高：数据区里碰巧出现同一个字节是常有的事。
//   两字节把误判概率从 1/256 降到 1/65536，再叠一层 CRC16，
//   整体误判概率约 1 / 2^32，工程上可忽略。
//
//   选值依据（数据区里几乎不可能出现）：
//     0xAA = 10101010
//     0x55 = 01010101
//   两者是互补的交替位模式。本协议数据区全是 float，
//   小端存放时最高字节是「符号+指数」，集中在 0x3F / 0x40 / 0xBF / 0xC0，
//   其余为尾数字节，不会出现这种规则交替模式。
//   实测：1.0 -> 00 00 80 3F，2.0 -> 00 00 00 40，均不含 AA/55。
//
// ============================================================================
// CRC 覆盖范围（联调前双方确认一致）
// ============================================================================
//
//   默认不含帧头：参与 CRC 的字节 = 命令字 + 长度 + 数据
//   若电控要含帧头，把下面的 CRC_START_OFFSET 改成 0。
//   两边不一致则全部帧校验失败。
//
// ============================================================================
// 命令表
// ============================================================================
//
//   命令字  方向          含义       数据区                      长度
//   0x01    上位机→电控   速度指令   vx(4B) + vy(4B) + wz(4B)    12 B
//           舵轮逆运动学（车体速度 -> 各轮转向角+转速）由电控固件完成
//   0x02    上位机→电控   急停       无                           0 B
//   0x10    电控→上位机   舵轮状态   4 轮 ×(角度4B + 转速4B)      32 B
//
//   其余命令字空间预留（本轮无机构命令）。
//
// ============================================================================
// 坐标系与单位（必须遵守）
// ============================================================================
//
//   vx : 车体前向速度 m/s，车头方向为正
//   vy : 车体左向速度 m/s，车体左侧为正
//   wz : 绕车体 Z 轴角速度 rad/s，俯视逆时针为正（ROS REP-103）
//
//   协议不做任何取负或换轴。装机后方向不对，改上位机 ROS 参数
//   invert_vx / invert_vy / invert_wz / swap_xy，不要改固件。
//
#pragma once

#include <cstddef>
#include <cstdint>

namespace rc27 {

// ============================================================================
// 物理层与帧常量
// ============================================================================
constexpr uint32_t UART_BAUDRATE = 115200;

/// 串口断开后的重连间隔（协议不做规定，属于上位机链路策略）
constexpr uint32_t RECONNECT_INTERVAL_MS = 500;

/// 帧头：两字节，交替位模式，数据区（float）里几乎不可能出现
constexpr uint8_t FRAME_HEADER_0 = 0xAA;  // 10101010
constexpr uint8_t FRAME_HEADER_1 = 0x55;  // 01010101

/// 帧固定开销：帧头(2) + 命令字(1) + 长度(1) + CRC(2) = 6
constexpr size_t FRAME_OVERHEAD = 6;
constexpr size_t MIN_FRAME_SIZE = FRAME_OVERHEAD;  // 无数据区时的帧长
constexpr size_t MAX_DATA_SIZE = 64;               // 数据区最大字节数

/// 舵轮数量（左前 / 右前 / 左后 / 右后）
constexpr size_t STEER_WHEEL_COUNT = 4;

/// CRC 计算起始偏移：2 = 从命令字开始（不含帧头）；0 = 含帧头
constexpr size_t CRC_START_OFFSET = 2;

// ============================================================================
// 命令字
// ============================================================================
enum class CommandID : uint8_t {
    SPEED_CMD = 0x01,    // 上位机→电控：车体速度指令 vx / vy / wz
    ESTOP = 0x02,        // 上位机→电控：急停（无数据区）
    STEER_STATE = 0x10,  // 电控→上位机：舵轮状态反馈
};

// ============================================================================
// 数据区定义
// ============================================================================

/// 0x01 速度指令：12 字节（车体坐标系）
struct SpeedCmdData {
    float vx{0.0f};  // 前向速度 m/s，单轴范围 [-3.0, 3.0]
    float vy{0.0f};  // 左向速度 m/s，单轴范围 [-3.0, 3.0]
    float wz{0.0f};  // 逆时针角速度 rad/s，范围 [-5.0, 5.0]
};
constexpr size_t SPEED_CMD_DATA_SIZE = 12;

/// 上位机保证：|vx| <= 3.0, |vy| <= 3.0, hypot(vx,vy) <= 3.0, |wz| <= 5.0
constexpr float LINEAR_AXIS_LIMIT = 3.0f;
constexpr float LINEAR_MAG_LIMIT = 3.0f;
constexpr float ANGULAR_LIMIT = 5.0f;

/// 0x10 舵轮状态反馈：32 字节（4 个舵轮，每轮一组「转向角 + 轮速」）
///
///   角度：rad，范围 [-π, π]，0 = 与车头同向，逆时针为正
///   轮速：m/s，轮子滚动前进方向为正
///
/// 舵轮必须回传转向角：只给轮速算不出里程——转向角偏差和侧向打滑都不可观，
/// 轮速积分误差会迅速发散。
struct SteerWheelData {
    float angle[STEER_WHEEL_COUNT];  // 四个舵轮当前转向角 rad
    float speed[STEER_WHEEL_COUNT];  // 四个舵轮当前轮速 m/s
};
constexpr size_t STEER_WHEEL_DATA_SIZE = 32;

// ============================================================================
// CRC-16/Modbus
// ============================================================================
// 多项式 0xA001（反射形式），初值 0xFFFF，无最终异或，结果低字节先发。
inline uint16_t crc16Modbus(const uint8_t* data, size_t length) {
    uint16_t crc = 0xFFFF;
    for (size_t i = 0; i < length; ++i) {
        crc ^= static_cast<uint16_t>(data[i]);
        for (int j = 0; j < 8; ++j) {
            if (crc & 0x0001) {
                crc = (crc >> 1) ^ 0xA001;
            } else {
                crc >>= 1;
            }
        }
    }
    return crc;
}

/// 给定数据区长度，返回整帧字节数
constexpr size_t frameSize(size_t data_size) { return data_size + FRAME_OVERHEAD; }

}  // namespace rc27
